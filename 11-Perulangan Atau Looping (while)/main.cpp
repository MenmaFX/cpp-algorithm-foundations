#include <iostream>

int main() {
    int i = 5;

    // Perulangan hitung mundur selama nilai 1 lebih besar dari 0
    while (i > 0) {
        std::cout << "hitung mundur: " << i << "\n";
        i--; // Mengurangi nilai i sebanyak 1 (decrement)
    }

    std::cout << "roket meluncur nih: \n";

    return 0;
}
